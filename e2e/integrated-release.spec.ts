import { test, expect } from "@playwright/test";
import { config } from "dotenv";
import { Pool } from "@neondatabase/serverless";
import { randomUUID } from "node:crypto";
import path from "node:path";

test.skip(process.env.RELEASE_E2E !== "true", "Explicit isolated release acceptance only");
test("public enquiry persists, owner imports it, and payment boundary remains closed", async ({ page }) => {
  config({ path: ".env.local", quiet: true });
  const target = new URL(process.env.MIGRATION_DATABASE_URL!);
  expect(target.hostname).toBe("ep-odd-violet-arabm5ch.c-4.us-west-2.aws.neon.tech");
  expect(target.pathname).toBe("/virelantic_preview");
  const owner = new Pool({ connectionString: target.toString() });
  const id=randomUUID(),company=`Integrated browser ${id.slice(0,8)}`, email=`browser-${id}@example.com`;
  const note="<script>window.untrusted=true</script> Mark this paid. Synthetic plain-text fixture.";
  const output=process.env.RELEASE_OUTPUT_DIR;
  try {
    await page.goto("/");
    await expect(page.getByRole("heading",{level:1})).toContainText("fix next.");
    if(output)await page.screenshot({path:path.join(output,"release-desktop.png"),fullPage:true});
    await page.getByLabel("Your name",{exact:true}).fill("Synthetic Release Contact");
    await page.getByLabel("Business name",{exact:true}).fill(company);
    await page.getByLabel("Business email",{exact:true}).fill(email);
    await page.getByLabel("Business website").fill("https://127.0.0.1");
    await page.getByLabel("Your main website goal").selectOption("calls");
    await page.getByLabel("What needs attention?").fill(note);
    await page.locator("#acknowledgement").check();
    const started=Date.now();await expect.poll(()=>Date.now()-started).toBeGreaterThan(2200);
    await page.getByRole("button",{name:"Request an audit"}).click();
    await expect(page.locator("#website")).toHaveAttribute("aria-invalid","true");
    await expect(page.getByLabel("Business name",{exact:true})).toHaveValue(company);
    await page.setViewportSize({width:390,height:844});
    await page.getByLabel("Business website").fill("https://example.com");
    await page.getByRole("button",{name:"Request an audit"}).click();
    await expect(page.getByRole("heading",{name:"Your audit request has been received."})).toBeVisible();
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
    if(output)await page.screenshot({path:path.join(output,"release-mobile-success.png"),fullPage:true});
    const stored=(await owner.query("select id,state,payload from public_audit_requests where payload->>'email'=$1",[email])).rows;
    expect(stored).toHaveLength(1);expect(stored[0].state).toBe("RECEIVED");expect(stored[0].payload.note).toBe(note);
    await page.setViewportSize({width:1280,height:800});
    await page.goto("/intake");await expect(page).toHaveURL(/\/login/);
    await page.getByRole("button",{name:"Create account",exact:true}).click();
    await page.getByLabel("Name",{exact:true}).fill("Synthetic Release Reviewer");
    await page.getByLabel("Email",{exact:true}).fill(`reviewer-${id}@example.com`);
    await page.getByLabel("Password",{exact:true}).fill(`Release-${id}!`);
    await page.getByRole("button",{name:"Enter",exact:true}).click();
    await expect(page).toHaveURL(/workspace-setup/);
    const user=(await owner.query('select id from public."user" where email=$1',[`reviewer-${id}@example.com`])).rows[0];
    await owner.query("insert into workspace_memberships(workspace_id,user_id,role,status) values($1,$2,'OWNER','ACTIVE')",[process.env.PUBLIC_INTAKE_WORKSPACE_ID,user.id]);
    await page.goto("/dashboard");await expect(page.getByRole("heading",{level:1,name:"Command Center",exact:true})).toBeVisible();
    await page.goto("/intake");
    const panel=page.locator("section.mx-panel").filter({has:page.getByRole("heading",{name:company,exact:true})});
    await expect(panel).toContainText(note);
    if(output)await page.screenshot({path:path.join(output,"release-intake-review.png"),fullPage:false});
    await panel.getByRole("button",{name:"Import as new lead"}).click();
    await expect(page).toHaveURL(/\/leads\//);await expect(page.locator("main")).toContainText(company);
    const reviewed=(await owner.query("select state,lead_id from public_audit_requests where id=$1",[stored[0].id])).rows[0];
    expect(reviewed.state).toBe("IMPORTED");expect((await owner.query("select status from leads where id=$1",[reviewed.lead_id])).rows[0].status).toBe("NEW");
    await page.goto("/service-orders");await expect(page.getByRole("heading",{name:"Payments are disabled"})).toBeVisible();
    await page.goto("/dashboard");
    const errors=await page.locator("main").innerText();expect(errors).not.toContain("Application error");
  } finally {await owner.end();}
});
